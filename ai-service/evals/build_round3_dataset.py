def main() -> None:
    rows = []
    counter = 1
    for category, level, include_arabic, messages in GROUPS:
        for message in messages:
            rows.append(
                {
                    "id": f"r3_msg_{counter:03d}",
                    "category": category,
                    "level": level,
                    "includeArabic": include_arabic,
                    "message": message,
                }
            )
            counter += 1

    if len(rows) != 200:
        raise RuntimeError(f"Expected 200 rows, got {len(rows)}")

    with OUT_PATH.open("w", encoding="utf-8") as handle:
        for row in rows:
            handle.write(json.dumps(row, ensure_ascii=False) + "\n")

    print(OUT_PATH)


if __name__ == "__main__":
    main()
